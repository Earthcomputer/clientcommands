    @TestCase
    private static void testEnchantmentCracking(ClientGameTestContext context, TestSingleplayerContext singleplayerContext) {
        runTest(context, singleplayerContext, () -> {
            setUpEnchantingTable(singleplayerContext, 15);
            openEnchantingTable(context, singleplayerContext);

            // The first XP seed tells us nothing about the player RNG since we don't know when it was generated
            crackXpSeed(context, singleplayerContext);
            enchantAndCheckPrediction(context, singleplayerContext, 2);
            assertPlayerCrackState(context, PlayerRandCracker.CrackState.ENCH_CRACKING_1);

            crackXpSeed(context, singleplayerContext);
            assertPlayerCrackState(context, PlayerRandCracker.CrackState.HALF_CRACKED);
            enchantAndCheckPrediction(context, singleplayerContext, 2);
            assertPlayerCrackState(context, PlayerRandCracker.CrackState.ENCH_CRACKING_2);

            crackXpSeed(context, singleplayerContext);
            assertPlayerCrackState(context, PlayerRandCracker.CrackState.CRACKED);
            assertPlayerSeedInSync(context, singleplayerContext);

            // Now that the player RNG is cracked, the next XP seed should be known straight away
            enchantAndCheckPrediction(context, singleplayerContext, 2);
            assertPlayerCrackState(context, PlayerRandCracker.CrackState.CRACKED);
            assertEquals(EnchantmentCracker.CrackState.CRACKED, context.computeOnClient(_ -> Configs.enchCrackState), () -> "Expected XP seed to be cracked");
            assertPlayerSeedInSync(context, singleplayerContext);
        });
    }

    @TestCase
    private static void testEnchantingOutcomes(ClientGameTestContext context, TestSingleplayerContext singleplayerContext) {
        for (SeedConfig config : SEED_CONFIGS) {
            runTest(context, singleplayerContext, config.toString(), () -> {
                setUpEnchantingTable(singleplayerContext, config.bookshelves);

                List<String> failures = new ArrayList<>();
                List<String> actualOutcomes = new ArrayList<>();
                for (Item item : ENCHANTABLE_ITEMS) {
                    assertTrue(new ItemStack(item).isEnchantable(), () -> item + " is not enchantable");
                    for (int slot = 0; slot < 3; slot++) {
                        // The enchanting menu only reads the player's XP seed when it's opened, so prime it before opening
                        closeContainer(context, singleplayerContext);
                        primeXpSeed(context, singleplayerContext, config.playerSeed);
                        openEnchantingTable(context, singleplayerContext);
                        putItemInTable(context, singleplayerContext, new ItemStack(item));
                        String outcome;
                        try {
                            outcome = enchantAndCheckPrediction(context, singleplayerContext, slot);
                        } catch (AssertionError e) {
                            failures.add(e.getMessage());
                            continue;
                        }
                        String key = outcomeKey(item, config, slot);
                        actualOutcomes.add("outcome(Items.%s, %dL, %d, %d, \"%s\"),".formatted(
                            BuiltInRegistries.ITEM.getKey(item).getPath().toUpperCase(Locale.ROOT), config.playerSeed, config.bookshelves, slot, outcome
                        ));
                        String expected = EXPECTED_OUTCOMES.get(key);
                        if (!outcome.equals(expected)) {
                            failures.add("Unexpected outcome for " + key + ": expected \"" + expected + "\", got \"" + outcome + "\"");
                        }
                    }
                }

                if (!failures.isEmpty()) {
                    LOGGER.error("Actual enchanting outcomes for {}:\n{}", config, String.join("\n", actualOutcomes));
                    throw new AssertionError(String.join("\n", failures));
                }
            });
        }
    }

    private static Map.Entry<String, String> outcome(Item item, long playerSeed, int bookshelves, int slot, String outcome) {
        return Map.entry(outcomeKey(item, new SeedConfig(playerSeed, bookshelves), slot), outcome);
    }

    private static String outcomeKey(Item item, SeedConfig config, int slot) {
        return BuiltInRegistries.ITEM.getKey(item) + "[" + config + ",slot=" + slot + "]";
    }

    static void setUpEnchantingTable(TestSingleplayerContext singleplayerContext, int bookshelves) {
        setBlock(singleplayerContext, TABLE_POS, Blocks.ENCHANTING_TABLE);
        List<BlockPos> offsets = EnchantingTableBlock.BOOKSHELF_OFFSETS;
        for (int i = 0; i < bookshelves; i++) {
            setBlock(singleplayerContext, TABLE_POS.offset(offsets.get(i)), Blocks.BOOKSHELF);
        }
        singleplayerContext.getServer().runOnServer(_ -> singleplayerContext.getConnection().getServerPlayer().setExperienceLevels(1000));
        singleplayerContext.getConnection().waitForClientboundPackets();
    }

    static void openEnchantingTable(ClientGameTestContext context, TestSingleplayerContext singleplayerContext) {
        useItemOnBlock(context, TABLE_POS);
        singleplayerContext.getConnection().waitForServerboundPackets();
        singleplayerContext.getConnection().waitForClientboundPackets();
        context.waitForScreen(EnchantmentScreen.class);
    }

    static void closeContainer(ClientGameTestContext context, TestSingleplayerContext singleplayerContext) {
        context.runOnClient(client -> Objects.requireNonNull(client.player).closeContainer());
        singleplayerContext.getConnection().waitForServerboundPackets();
    }

    // Puts the item in the enchanting table, along with plenty of lapis and levels
    static void putItemInTable(ClientGameTestContext context, TestSingleplayerContext singleplayerContext, ItemStack stack) {
        singleplayerContext.getServer().runOnServer(_ -> {
            ServerPlayer player = singleplayerContext.getConnection().getServerPlayer();
            player.setExperienceLevels(1000);
            EnchantmentMenu menu = (EnchantmentMenu) player.containerMenu;
            menu.getSlot(1).set(new ItemStack(Items.LAPIS_LAZULI, 64));
            menu.getSlot(0).set(stack);
            menu.broadcastChanges();
        });
        singleplayerContext.getConnection().waitForClientboundPackets();
        context.waitTick();
    }

    // Sets the player seed to a known value, then generates the XP seed from it, as if the player had enchanted an item
    static void primeXpSeed(ClientGameTestContext context, TestSingleplayerContext singleplayerContext, long playerSeed) {
        setKnownPlayerSeed(context, singleplayerContext, playerSeed);
        singleplayerContext.getServer().runOnServer(_ -> singleplayerContext.getConnection().getServerPlayer().onEnchantmentPerformed(ItemStack.EMPTY, 0));
        context.runOnClient(_ -> PlayerRandCracker.onEnchantedItem());
    }

    private static void crackXpSeed(ClientGameTestContext context, TestSingleplayerContext singleplayerContext) {
        for (Item item : CRACKING_ITEMS) {
            putItemInTable(context, singleplayerContext, new ItemStack(item));
            context.clickScreenButton("enchCrack.addInfo");
            if (context.computeOnClient(_ -> Configs.enchCrackState) != EnchantmentCracker.CrackState.CRACKING) {
                break;
            }
        }
        assertEquals(EnchantmentCracker.CrackState.CRACKED, context.computeOnClient(_ -> Configs.enchCrackState), () -> "Failed to crack the XP seed");
    }

    // Clicks the given enchantment slot, checks the client predicted the outcome correctly, and returns a description of the outcome
    static String enchantAndCheckPrediction(ClientGameTestContext context, TestSingleplayerContext singleplayerContext, int slot) {
        record Prediction(int cost, @Nullable String enchantments) {
        }

        Prediction prediction = context.computeOnClient(client -> {
            EnchantmentMenu menu = ((EnchantmentScreen) Objects.requireNonNull(client.gui.screen())).getMenu();
            boolean cracked = Configs.enchCrackState == EnchantmentCracker.CrackState.CRACKED;
            List<EnchantmentInstance> enchantments = cracked ? EnchantmentCracker.getEnchantmentsInTable(slot, menu) : null;
            return new Prediction(menu.costs[slot], enchantments == null ? null : describeEnchantments(enchantments));
        });

        if (prediction.cost == 0) {
            return "0:";
        }

        context.runOnClient(client -> {
            LocalPlayer player = Objects.requireNonNull(client.player);
            EnchantmentMenu menu = (EnchantmentMenu) player.containerMenu;
            assertTrue(menu.clickMenuButton(player, slot), () -> "Could not click enchantment slot " + slot);
            Objects.requireNonNull(client.gameMode).handleInventoryButtonClick(menu.containerId, slot);
        });
        singleplayerContext.getConnection().waitForServerboundPackets();
        singleplayerContext.getConnection().waitForClientboundPackets();

        String actual = singleplayerContext.getServer().computeOnServer(_ -> {
            ItemStack result = singleplayerContext.getConnection().getServerPlayer().containerMenu.getSlot(0).getItem();
            List<EnchantmentInstance> enchantments = new ArrayList<>();
            for (var entry : EnchantmentHelper.getEnchantmentsForCrafting(result).entrySet()) {
                enchantments.add(new EnchantmentInstance(entry.getKey(), entry.getIntValue()));
            }
            return describeEnchantments(enchantments);
        });

        if (prediction.enchantments != null) {
            assertEquals(prediction.enchantments, actual, () -> "Enchantment prediction for slot " + slot + " was \"" + prediction.enchantments + "\", but the actual enchantments were \"" + actual + "\"");
        }

        return prediction.cost + ":" + actual;
    }

    private static String describeEnchantments(List<EnchantmentInstance> enchantments) {
        return enchantments.stream()
            .map(ench -> enchantmentId(ench.enchantment()) + " " + ench.level())
            .sorted()
            .collect(Collectors.joining(", "));
    }

    private static String enchantmentId(Holder<Enchantment> enchantment) {
        return enchantment.unwrapKey().orElseThrow().identifier().getPath();
    }
